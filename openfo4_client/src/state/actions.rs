#[derive(Clone, Debug, Default)]
pub struct Actions(pub HashMap<Action, RecordId>);

impl Actions {
    pub async fn load(loader: &EspLoader) -> Self {
        let records = loader.lookup_all(Some(RecordKind::Action)).await.unwrap();

        let mut actions = HashMap::new();

        for record in records {
            let RecordData::Action(data) = record.local.data else {
                continue;
            };

            let Some(name) = data.id.as_ref().map(|v| v.as_str()).flatten() else {
                continue;
            };

            let Ok(action) = name.parse() else {
                tracing::warn!("unknown action name {}, will be ignored", name);
                continue;
            };

            actions.insert(action, record.id);
        }

        Self(actions)
    }
}
